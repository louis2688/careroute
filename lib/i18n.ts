// Two languages, two URL trees: English at "/", Spanish at "/es". Small UI strings live here;
// long-form copy lives in lib/site.ts (en) and lib/site.es.ts (es).
export type Lang = "en" | "es";

export const langFromPath = (path: string): Lang => (path === "/es" || path.startsWith("/es/") ? "es" : "en");
export const href = (lang: Lang, path: string) => (lang === "es" ? (path === "/" ? "/es" : `/es${path}`) : path);
export const switchPath = (path: string, to: Lang) => {
  const bare = path === "/es" ? "/" : path.startsWith("/es/") ? path.slice(3) : path;
  return href(to, bare);
};

